"""Regenerate the evidence report from the supplied CSV, without desired-total targets."""
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

from classifier import SPEC_POLICY, classify, read_history

ROOT = Path(__file__).resolve().parent


def main():
    data = (ROOT / "data/run_history.csv").read_bytes()
    history = read_history(data.decode("utf-8-sig"))
    results = classify(history)
    baseline = {r.workflow: r for r in classify(history, SPEC_POLICY)}
    counts = Counter(r.decision for r in results)
    output = {"dataset_sha256": hashlib.sha256(data).hexdigest(),
              "counts": dict(counts), "results": [r.to_dict() for r in results]}
    (ROOT / "data/classification_results.json").write_text(json.dumps(output, indent=2) + "\n")
    with (ROOT / "data/classification_results.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["workflow", "cadence", "decision", "routing", "run_count",
                                             "first_start", "last_start", "evidence", "warnings", "likely_retry_rows"])
        writer.writeheader()
        for r in results:
            row = r.to_dict()
            writer.writerow({k: " | ".join(map(str, row[k])) if isinstance(row[k], list) else row[k]
                             for k in writer.fieldnames})
    lines = ["# Actual dataset validation", "", "Generated by `python validate_dataset.py`. System inference only; no manual corrections applied.",
             "", f"Input SHA-256: `{output['dataset_sha256']}`.", "",
             f"{sum(history.row_counts.values())} rows; {len(results)} workflows. " +
             "; ".join(f"**{counts[d]} {d}**" for d in ("In scope", "Too frequent", "Unknown")) + ".", "",
             "| Workflow | Inferred cadence | Decision | Likely retries |", "|---|---|---|---:|"]
    lines += [f"| {r.workflow} | {r.cadence} | {r.decision} | {len(r.likely_retry_rows)} |" for r in results]
    changes = [r.workflow for r in results if r.decision != baseline[r.workflow].decision]
    lines += ["", "## Evidence-threshold sensitivity", "",
              "Original SPEC evidence counts, with the same corrected boundary/calendar/retry logic: " +
              "; ".join(f"{n} {d}" for d, n in sorted(Counter(r.decision for r in baseline.values()).items())) + ".",
              "Decision changes on the actual CSV: " + (", ".join(changes) if changes else "none") + ".", "",
              "The provisional 30/3/7 split was not an expected answer. The implemented third-business-day monthly "
              "rule admits wf_FIN_BUDGET_ACTUALS (Jul 3, Aug 5, Sep 3). Removing that documented calendar extension "
              "would return it to Unknown and produce 30/3/7; the shorter evidence gates do not explain the difference.",
              "", "## Workflows requiring engineer review", ""]
    for r in results:
        if r.decision != "In scope":
            lines += [f"### {r.workflow}: {r.decision}", "", f"{r.run_count} runs; {r.first_start} → {r.last_start}.",
                      "", *["- " + e for e in r.evidence], ""]
    lines += ["## Inactivity and health", ""]
    for r in results:
        relevant = [w for w in r.warnings if "inactivity" in w or "Execution health" in w or "Gaps" in w]
        if relevant:
            lines.append(f"- **{r.workflow}**: " + " ".join(relevant))
    lines += ["", "Every workflow's full evidence, warnings and original CSV retry row references are in "
              "`data/classification_results.json` and `.csv`. Health/inactivity do not change frequency eligibility.", ""]
    (ROOT / "docs/results.md").write_text("\n".join(lines))
    print("; ".join(f"{counts[d]} {d}" for d in ("In scope", "Too frequent", "Unknown")))


if __name__ == "__main__":
    main()
